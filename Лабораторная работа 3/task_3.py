def calculate_frequency(counts):
    """
    Вычисляет частоту каждой буквы.
    """
    total_letters = sum(counts.values())  # Общее количество букв
    if total_letters == 0:
        return {}  # Если букв нет, возвращаем пустой словарь
    frequencies = {
        char: round(count / total_letters, 2)  # Округляем до 2 знаков
        for char, count in counts.items()
    }
    return frequencies


